"""Summarise the parity suite from a run: fixture cases, tolerances and measured differences.

Runs the whole test suite in this process with a plugin that records every
``spynach.oracle.compare`` call, together with the test it came from, and
lists the fixture cases on disk. It then writes

    oracle/parity_summary.json   counts and the largest measured difference per tolerance
    docs/parity.md               the tolerance policy, a summary table per family, and
                                 the full table (case, quantity, tolerance, measured error)
    spinach.html                 the paragraph between <!-- parity-summary --> markers

so that the numbers on the project site and in the documentation come from
the suite rather than from a keyboard. It refuses to write when a parity
test skipped, which means a fixture case was missing and the numbers would
understate the suite.

    OPENBLAS_NUM_THREADS=4 PYTHONPATH=src python oracle/parity_summary.py [--check]

``--check`` only compares the three outputs with what the committed JSON
renders to (no test run), which is what tests/oracle/test_parity_summary.py does;
``--render`` rewrites them from the committed JSON (after a change to the layout).
Failures outside the parity suite (a stale notebook, say) are reported but
do not block the summary; a failed or skipped parity test does.
"""

from __future__ import annotations

import argparse
import importlib
import json
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

JSON = ROOT / "oracle" / "parity_summary.json"
PARITY_MD = ROOT / "docs" / "parity.md"
PAGE = ROOT / "spinach.html"
MARKERS = ("<!-- parity-summary -->", "<!-- /parity-summary -->")
PARITY_TESTS = ["tests/slice", "tests/oracle/test_hilb_pa_fixtures.py"]


@dataclass(frozen=True)
class Family:
    label: str
    prefix: str  # fixture case name prefix; the longest matching prefix wins
    files: tuple[str, ...]  # test files, relative to the repository root


FAMILIES = [
    Family("Liouville-space setup", "liouv_", ("tests/slice/test_liouv_setup_parity.py",)),
    Family("Liouville-space propagation", "liouv_pa_", ("tests/slice/test_liouv_pa_parity.py",)),
    Family(
        "Hilbert-space pulse-acquire",
        "hilb_pa_",
        ("tests/slice/test_hilb_pa_parity.py", "tests/oracle/test_hilb_pa_fixtures.py"),
    ),
    Family("anisotropic interactions", "aniso_", ("tests/slice/test_aniso_parity.py",)),
    Family("relaxation", "relax_", ("tests/slice/test_relax_parity.py",)),
    Family("scalar relaxation", "scalar_", ("tests/slice/test_scalar_parity.py",)),
    Family("magic angle spinning", "mas_", ("tests/slice/test_mas_parity.py",)),
    Family("pulse sequences", "seq_", ("tests/slice/test_seq_parity.py",)),
]

POLICY = """\
# Parity with Spinach: cases, tolerances, measured differences

*Generated by `oracle/parity_summary.py` from a run of the test suite; do not edit.*

Every parity test recomputes the intermediate results of a reference case and
compares them with the output of Spinach {tag}, stored as fixtures (see
[`oracle/README.md`](../oracle/README.md) for how fixtures are produced and
loaded). The comparison is normwise, `||actual - expected|| <= atol + rtol * ||expected||`
in the Frobenius norm, through `spynach.oracle.compare`.

**Tolerance policy.** Comparisons are relative, with `atol = 0`, so that they
survive a change of BLAS or FFT backend, of hardware, or of summation order
without ever passing on a result that is wrong. The tolerance follows the
kind of quantity, not the case:

- **Exact** (`rtol = 0`) only for quantities that are exact by construction:
  basis tables, filters and masks, rate matrices copied from the input, and
  spin-1/2 operator elements (0, 1 and one half).
- **1e-15 to 1e-14** for constructed quantities: operators, states, grids and
  spectral derivatives. The measured difference is at most a few ulp; Spinach
  evaluates `2^(-1/2)` one ulp below the correctly rounded value.
- **1e-13 to 1e-10** for Hamiltonians, superoperators and single propagators,
  which sum many terms. Spinach rounds Hamiltonian elements to a 1e-10 rad/s
  grid after summing in random order, so Spinach itself reproduces only to one
  grid step per element.
- **1e-9** for everything that goes through a time evolution or an FID: the
  Taylor propagator's error scales with `tols.prop_chop`, and the grid rounding
  above gives about 1e-10 x acquisition time in an FID.

The tables below give, for every comparison the suite makes, the tolerance it
uses and the difference it measured on {date}. Any relative tolerance that is
hundreds of times larger than the measured difference is margin for other
machines, not slack in the port. For checking your own results against a
Spinach run, see [Checking your own workflow against
Spinach](coming-from-spinach.md#checking-your-own-workflow-against-spinach).
"""


class Recorder:
    """pytest plugin: records every comparison with the test it was made in, and test outcomes."""

    def __init__(self) -> None:
        self.records: list[tuple[str, object]] = []
        self.current: str | None = None
        self.outcomes: dict[str, str] = {}
        self.items: list[str] = []

    def pytest_collection_finish(self, session) -> None:
        self.items = [item.nodeid for item in session.items]

    def pytest_runtest_logstart(self, nodeid, location) -> None:
        self.current = nodeid

    def pytest_runtest_logreport(self, report) -> None:
        if report.when == "call" or report.skipped:
            self.outcomes[report.nodeid] = report.outcome

    def record(self, comparison) -> None:
        self.records.append((self.current or "", comparison))


def family_of_case(case: str) -> Family | None:
    hits = [f for f in FAMILIES if case.startswith(f.prefix)]
    return max(hits, key=lambda f: len(f.prefix)) if hits else None


def family_of_test(nodeid: str) -> Family | None:
    path = nodeid.split("::")[0]
    return next((f for f in FAMILIES if path in f.files), None)


def fixture_cases() -> tuple[str, list[str]]:
    """Fixture tag and the case directories under it."""
    from spynach.oracle.fixture import fixture_root

    tags = sorted(p for p in fixture_root().iterdir() if p.is_dir())
    if len(tags) != 1:
        raise SystemExit(f"expected one fixture tag under {fixture_root()}, found {[t.name for t in tags]}")
    cases = sorted(p.name for p in tags[0].iterdir() if (p / "data.h5").exists())
    return tags[0].name, cases


def case_of_test(nodeid: str, family: Family, cases: set[str]) -> str:
    """The fixture case a parametrised test ran on: the family prefix plus the parameter id."""
    match = re.search(r"\[([^\]]+)\]$", nodeid)
    if match:
        for candidate in (family.prefix + match.group(1), match.group(1)):
            if candidate in cases:
                return candidate
        return match.group(1)
    return ""


def collect() -> dict:
    """Run the suite and return the summary dictionary."""
    import pytest

    compare_module = importlib.import_module("spynach.oracle.compare")  # the module, not the function

    recorder = Recorder()
    compare_module.RECORDER = recorder.record
    try:
        code = pytest.main(["-q", "-p", "no:cacheprovider", "tests"], plugins=[recorder])
    finally:
        compare_module.RECORDER = None
    parity_items = [i for i in recorder.items if family_of_test(i) is not None]
    for outcome in ("failed", "skipped"):
        bad = [i for i in parity_items if recorder.outcomes.get(i) == outcome]
        if bad:
            raise SystemExit(f"{len(bad)} parity tests {outcome} (fixtures missing?), e.g. {bad[0]}; nothing written")
    if code != 0:
        print(f"note: pytest exit code {code} from tests outside the parity suite (see above); the summary is written")

    tag, cases = fixture_cases()
    case_set = set(cases)
    rows = []
    for nodeid, comparison in recorder.records:
        family = family_of_test(nodeid)
        if family is None:
            continue
        rows.append(
            {
                "family": family.label,
                "case": case_of_test(nodeid, family, case_set),
                "test": nodeid.split("::", 1)[1],
                "quantity": comparison.name or "",
                "shape": list(comparison.shape),
                "rtol": comparison.rtol,
                "atol": comparison.atol,
                "rel_err": comparison.rel_err,
            }
        )
    families = []
    for family in FAMILIES:
        own = [r for r in rows if r["family"] == family.label]
        worst: dict[str, float] = defaultdict(float)
        for r in own:
            key = f"{r['rtol']:g}"
            worst[key] = max(worst[key], r["rel_err"])
        families.append(
            {
                "label": family.label,
                "tests": sum(family_of_test(i) is family for i in parity_items),
                "cases": sorted(c for c in cases if family_of_case(c) is family),
                "comparisons": len(own),
                "worst_by_rtol": dict(sorted(worst.items(), key=lambda kv: -float(kv[0]))),
            }
        )
    worst_all: dict[str, float] = defaultdict(float)
    for r in rows:
        key = f"{r['rtol']:g}"
        worst_all[key] = max(worst_all[key], r["rel_err"])
    return {
        "generated": datetime.now(UTC).strftime("%Y-%m-%d"),
        "fixture_tag": tag,
        "tests": len(recorder.items),
        "parity_tests": len(parity_items),
        "fixture_cases": len(cases),
        "families": families,
        "worst_by_rtol": dict(sorted(worst_all.items(), key=lambda kv: -float(kv[0]))),
        "comparisons": sorted(rows, key=lambda r: (r["family"], r["case"], r["test"], r["quantity"])),
    }


def render_markdown(summary: dict) -> str:
    lines = [POLICY.format(tag=summary["fixture_tag"], date=summary["generated"])]
    lines.append("## Summary\n")
    lines.append(
        f"{summary['tests']} tests, of which {summary['parity_tests']} are fixture comparisons over "
        f"{summary['fixture_cases']} fixture cases.\n"
    )
    lines.append("| family | fixture cases | tests | comparisons | largest measured difference (at tolerance) |")
    lines.append("|---|---|---|---|---|")
    for f in summary["families"]:
        worst = ", ".join(f"{v:.1e} ({k})" for k, v in f["worst_by_rtol"].items() if float(k) > 0)
        exact = "exact" if "0" in f["worst_by_rtol"] else ""
        lines.append(
            f"| {f['label']} | {len(f['cases'])} | {f['tests']} | {f['comparisons']} | "
            f"{'; '.join(x for x in (worst, exact) if x)} |"
        )
    lines.append("")
    lines.append("## Every comparison\n")
    lines.append(
        "Relative difference `||actual - expected|| / ||expected||`; `0` is bit-exact. One table per family, folded.\n"
    )
    for f in summary["families"]:
        rows = [r for r in summary["comparisons"] if r["family"] == f["label"]]
        lines.append(
            f"<details><summary>{f['label']}: {len(rows)} comparisons over {len(f['cases'])} cases</summary>\n"
        )
        lines.append("| case | test | quantity | shape | rtol | atol | measured |")
        lines.append("|---|---|---|---|---|---|---|")
        for r in rows:
            shape = "x".join(str(n) for n in r["shape"]) if r["shape"] else "scalar"
            test = r["test"].split("[")[0]
            lines.append(
                f"| `{r['case']}` | `{test}` | `{r['quantity']}` | {shape} | {r['rtol']:g} | {r['atol']:g} | "
                f"{r['rel_err']:.1e} |"
            )
        lines.append("\n</details>\n")
    return "\n".join(lines) + "\n"


def render_paragraph(summary: dict) -> str:
    """The paragraph of the Spinach-port page, between the markers."""
    families = ", ".join(f"{f['label']} ({f['tests']})" for f in summary["families"])
    worst = {float(k): v for k, v in summary["worst_by_rtol"].items() if float(k) > 0}
    loose = max((v for k, v in worst.items() if k >= 1e-9), default=0.0)
    tight = max((v for k, v in worst.items() if k < 1e-9), default=0.0)
    tiers = (
        f"{loose:.0e} for quantities compared at 1e-9 (time evolution and FIDs) and {tight:.0e} for everything "
        f"compared at 1e-10 or tighter (operators, states, Hamiltonians, propagators)"
    ).replace("e-0", "e-")
    return (
        f"{MARKERS[0]}<p>The parity suites compare Spynach with Spinach {summary['fixture_tag']} fixtures at every "
        f"stage of a calculation. Of the {summary['tests']} tests, {summary['parity_tests']} are fixture comparisons "
        f"over {summary['fixture_cases']} fixture cases: {families}. Comparisons are relative with zero absolute "
        f"tolerance; the largest measured difference is {tiers}. Every case, tolerance and measured "
        f'difference is listed in <a href="https://github.com/ajerschow/spynach/blob/main/docs/parity.md">'
        f"docs/parity.md</a> (regenerated from the suite by <code>oracle/parity_summary.py</code>).</p>{MARKERS[1]}"
    )


def rendered_index(summary: dict, html: str) -> str:
    pattern = re.compile(re.escape(MARKERS[0]) + r".*?" + re.escape(MARKERS[1]), flags=re.S)
    if not pattern.search(html):
        raise SystemExit(f"{PAGE.name} has no {MARKERS[0]} ... {MARKERS[1]} span")
    return pattern.sub(lambda _: render_paragraph(summary), html, count=1)


def stale(summary: dict) -> list[str]:
    """Outputs that differ from what the summary renders to."""
    out = []
    if PARITY_MD.read_text(encoding="utf-8") != render_markdown(summary):
        out.append(str(PARITY_MD.relative_to(ROOT)))
    html = PAGE.read_text(encoding="utf-8")
    if rendered_index(summary, html) != html:
        out.append(str(PAGE.relative_to(ROOT)))
    return out


def collected_parity_tests() -> int:
    """Number of parity test items, from a pytest collection in a subprocess."""
    result = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider", *PARITY_TESTS],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return sum("::" in line for line in result.stdout.splitlines())


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare the outputs with the committed JSON, no run")
    parser.add_argument("--render", action="store_true", help="rewrite the outputs from the committed JSON, no run")
    args = parser.parse_args(argv)
    if args.check:
        summary = json.loads(JSON.read_text(encoding="utf-8"))
        outdated = stale(summary)
        for name in outdated:
            print(f"stale: {name}")
        return 1 if outdated else 0
    summary = json.loads(JSON.read_text(encoding="utf-8")) if args.render else collect()
    JSON.write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
    PARITY_MD.write_text(render_markdown(summary), encoding="utf-8")
    PAGE.write_text(rendered_index(summary, PAGE.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"{summary['tests']} tests, {summary['parity_tests']} parity tests, {summary['fixture_cases']} cases")
    for f in summary["families"]:
        print(f"  {f['label']}: {len(f['cases'])} cases, {f['tests']} tests, {f['comparisons']} comparisons")
    print("worst by tolerance:", summary["worst_by_rtol"])
    print(f"wrote {JSON.relative_to(ROOT)}, {PARITY_MD.relative_to(ROOT)}, {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
